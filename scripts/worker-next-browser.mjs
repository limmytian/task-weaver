import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
assert.ok(process.env.TW_PLAYWRIGHT_MODULE, 'TW_PLAYWRIGHT_MODULE is required');
const { chromium } = require(process.env.TW_PLAYWRIGHT_MODULE);
assert.ok(process.env.TW_LOCAL_ACCEPTANCE_METADATA, 'TW_LOCAL_ACCEPTANCE_METADATA is required');
const meta = JSON.parse(await readFile(process.env.TW_LOCAL_ACCEPTANCE_METADATA, 'utf8'));
assert.equal(new URL(meta.url).hostname, '127.0.0.1');
assert.equal(meta.synthetic, true, 'Only disposable synthetic acceptance data is allowed');
const credentials = await readFile(meta.credentials, 'utf8');
const browser = await chromium.launch({ executablePath: process.env.TW_BROWSER_EXECUTABLE, headless: true });
try {
  const page = await browser.newPage(); page.setDefaultTimeout(10000);
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(`${meta.url}/login`);
  await page.getByLabel('Email', {exact:true}).fill('acceptance@example.test');
  await page.getByLabel('Password', {exact:true}).fill(credentials.match(/^Password: (.+)$/m)[1]);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL('**/projects');
  await page.goto(`${meta.url}/projects/attention`);
  await page.getByRole('heading',{name:'Synthetic acceptance: interrupted Worker',exact:true}).waitFor();
  await page.getByRole('link',{name:'Inspect evidence and recovery controls',exact:true}).click();
  await page.getByText('Worker evidence and recovery',{exact:true}).click();
  await page.getByRole('link',{name:'Synthetic interrupted task: inspect and resolve',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await page.getByRole('link', { name: 'Synthetic interrupted task: inspect and resolve', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByText('Requirement review decisions:', { exact: false }).waitFor();
  await page.getByRole('link', { name: 'Inspect process reports and coverage', exact: true }).click();
  await page.getByText('unknown / synthetic-fixture', { exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('project'), meta.projectId);
  assert.equal(new URL(page.url()).searchParams.get('requirement'), meta.requirementId);
  await page.screenshot({ path: `${meta.root}/usage-page.png`, fullPage: true });
  assert.equal(errors.length,0,errors.join('; '));
  console.log(JSON.stringify({passed:true,scope:'actual Next.js login, attention, requirement recovery and linked task dialog',url:meta.url}));
} finally {await browser.close();}
