import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { resourcePostgresFixture } from '../apps/api/src/resource-postgres-fixture';
const require = createRequire(new URL('../apps/api/package.json', import.meta.url));
const { createDb, runMigrations, requirements, requirementDependencies, executionControls, tasks, tiAgentRuns, taskDependencies, projectMemberships } = require('@task-weaver/db');
const { createAttentionService } = require('@task-weaver/core');
const { eq, and } = require('drizzle-orm');
const databaseUrl = process.env.TW_ATTENTION_E2E_DATABASE_URL;

test('attention uses current scope, priority, bounded pages and live exit conditions', { skip: !databaseUrl, timeout: 120_000 }, async t => {
  const url = new URL(databaseUrl!);
  assert.equal(url.hostname, '127.0.0.1');
  assert.equal(url.pathname, '/tw_attention_e2e');
  await runMigrations(databaseUrl!);
  const db = createDb(databaseUrl!);
  t.after(() => db.$client.end());
  const f = await resourcePostgresFixture(db, databaseUrl!);
  const service = createAttentionService(f.owner.context);
  const foreign = await f.identity.createProject(f.outsider.headers, { name: 'Foreign' });
  const seed = async (title: string, values = {}) => (await db.insert(requirements).values({ title, projectId: f.project.id, createdBy: f.owner.context.actor.id, ...values }).returning())[0];
  const review = await seed('Review', { status: 'in_review' });
  const recovery = await seed('Recovery wins review', { status: 'in_review', evidenceNeedsReview: true });
  const failure = await seed('Failure', { workflowState: { delivery: 'failed' } });
  const upstream = await seed('Draft upstream');
  const blocked = await seed('Blocked');
  await db.insert(requirementDependencies).values({ requirementId: blocked.id, dependsOnRequirementId: upstream.id, type: 'blocks' });
  await seed('Foreign review', { projectId: foreign.id, status: 'in_review' });
  await seed('Closed', { status: 'done', evidenceNeedsReview: true });
  const page = await service.list(db, {});
  assert.deepEqual(new Set(page.items.map((x: any) => x.category)), new Set(['review', 'recovery', 'failure', 'blocked']));
  assert.equal(page.items.length, 4);
  assert.ok(page.items.every((x: any) => x.projectId === f.project.id && x.responsibility === 'available_to_you'));
  assert.equal(page.items.find((x: any) => x.requirementId === recovery.id).category, 'recovery');
  assert.equal((await service.list(db, { category: 'review' })).items.length, 1);
  await assert.rejects(service.list(db, { projectId: foreign.id }));
  await assert.rejects(service.list(db, { limit: 51 }));
  const seen = new Set();
  let after;
  do {
    const next = await service.list(db, { limit: 1, after });
    for (const item of next.items) { assert.ok(!seen.has(item.id)); seen.add(item.id); }
    after = next.next ?? undefined;
  } while (after);
  assert.equal(seen.size, 4);
  await db.update(requirements).set({ status: 'done' }).where(eq(requirements.id, upstream.id));
  assert.equal((await service.list(db, { category: 'blocked' })).items.length, 0);
  await db.update(requirements).set({ status: 'done' }).where(eq(requirements.id, review.id));
  assert.equal((await service.list(db, { category: 'review' })).items.length, 0);
  const execution = await seed('Failed execution');
  const [task] = await db.insert(tasks).values({ projectId: f.project.id, requirementId: execution.id, title: 'Execution task', createdBy: f.owner.context.actor.id }).returning();
  await db.insert(tiAgentRuns).values({ taskId: task.id, status: 'failed', createdBy: f.owner.context.actor.id, createdAt: new Date('2026-01-01') });
  assert.ok((await service.list(db, { category: 'failure' })).items.some((x: any) => x.requirementId === execution.id));
  await db.insert(tiAgentRuns).values({ taskId: task.id, status: 'succeeded', createdBy: f.owner.context.actor.id, createdAt: new Date('2026-01-02') });
  assert.ok(!(await service.list(db, { category: 'failure' })).items.some((x: any) => x.requirementId === execution.id));
  const [upstreamTask] = await db.insert(tasks).values({ projectId: f.project.id, requirementId: upstream.id, title: 'Task blocker', createdBy: f.owner.context.actor.id }).returning();
  await db.insert(taskDependencies).values({ taskId: task.id, dependsOnTaskId: upstreamTask.id, type: 'blocks' });
  assert.ok((await service.list(db, { category: 'blocked' })).items.some((x: any) => x.requirementId === execution.id));
  await db.update(tasks).set({ status: 'done' }).where(eq(tasks.id, upstreamTask.id));
  assert.ok(!(await service.list(db, { category: 'blocked' })).items.some((x: any) => x.requirementId === execution.id));
  const owner = f.owner.context.actor.id;
  await db.update(projectMemberships).set({ role: 'viewer' }).where(and(eq(projectMemberships.projectId, f.project.id), eq(projectMemberships.actorId, owner)));
  assert.ok((await service.list(db, {})).items.every((x: any) => !x.canAct));
  await db.delete(projectMemberships).where(and(eq(projectMemberships.projectId, f.project.id), eq(projectMemberships.actorId, owner)));
  assert.equal((await service.list(db, {})).items.length, 0);
  await assert.rejects(service.list(db, { projectId: f.project.id }));
});
