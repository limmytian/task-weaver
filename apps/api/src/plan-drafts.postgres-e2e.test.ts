import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { and, eq, sql } from "drizzle-orm";
import { createDb, runMigrations, requirements, documents, planDrafts } from "@task-weaver/db";
import { resourcePostgresFixture } from "./resource-postgres-fixture";

const databaseUrl = process.env.TW_PLAN_DRAFT_E2E_DATABASE_URL;
test("drafts persist, reject stale writes and validate against live dependencies", { skip: !databaseUrl, timeout: 120_000 }, async t => {
  const url = new URL(databaseUrl!);
  assert.equal(url.hostname, "127.0.0.1");
  assert.equal(url.pathname, "/tw_plan_drafts_e2e");
  await runMigrations(databaseUrl!);
  await runMigrations(databaseUrl!);
  const db = createDb(databaseUrl!);
  t.after(() => db.$client.end());
  const f = await resourcePostgresFixture(db, databaseUrl!);
  const api = (path: string, method = "GET", body?: unknown, headers = f.owner.headers) => f.app.request(`/api/v1${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const json = async (response: Response, status = 200): Promise<any> => { assert.equal(response.status, status, await response.clone().text()); return response.json(); };
  const projectId = f.project.id;
  const plan = { projectId, requirements: [{ key: "r", title: "New requirement", tasks: [{ key: "t", title: "New task" }] }] };
  const draft = await json(await api("/plans/drafts", "POST", { plan }), 201);
  assert.equal(draft.revision, 1);
  assert.equal((await json(await api(`/plans/drafts/${draft.id}?projectId=${projectId}`))).plan.requirements[0].title, "New requirement");
  assert.equal((await api(`/plans/drafts/${draft.id}?projectId=${projectId}`, "GET", undefined, f.outsider.headers)).status, 404);
  await f.identity.setMembership(f.owner.headers, projectId, f.outsider.context.actor.id, { role: "viewer", explicitPermissions: [] });
  const viewerDraft = await json(await api(`/plans/drafts/${draft.id}?projectId=${projectId}`, "GET", undefined, f.outsider.headers));
  assert.equal(viewerDraft.canWrite, false);
  assert.equal((await api(`/plans/drafts/${draft.id}`, "PUT", { projectId, revision: 1, plan }, f.outsider.headers)).status, 403);
  await f.identity.removeMembership(f.owner.headers, projectId, f.outsider.context.actor.id);
  assert.equal((await api(`/plans/drafts/${draft.id}?projectId=${projectId}`, "GET", undefined, f.outsider.headers)).status, 404);
  const results = await Promise.all([1, 2].map(i => api(`/plans/drafts/${draft.id}`, "PUT", { projectId, revision: 1, plan: { ...plan, requirements: [{ ...plan.requirements[0], title: `Edit ${i}` }] } })));
  assert.deepEqual(results.map(r => r.status).sort(), [200, 409]);
  const saved = await json(await api(`/plans/drafts/${draft.id}?projectId=${projectId}`));
  assert.equal(saved.revision, 2);
  assert.equal((await json(await api(`/plans/drafts/${draft.id}/validate`, "POST", { projectId }))).result.summary.tasks.create, 1);
  const a = await json(await api(`/projects/${projectId}/requirements`, "POST", { title: "A" }), 201);
  const b = await json(await api(`/projects/${projectId}/requirements`, "POST", { title: "B" }), 201);
  await json(await api(`/requirements/${a.id}/dependencies`, "POST", { dependsOnRequirementId: b.id, type: "blocks" }), 201);
  const cycle = { projectId, requirements: [{ key: "a", existingId: a.id }, { key: "b", existingId: b.id, dependsOn: ["a"] }] };
  await json(await api(`/plans/drafts/${draft.id}`, "PUT", { projectId, revision: 2, plan: cycle }));
  const invalid = await api(`/plans/drafts/${draft.id}/validate`, "POST", { projectId });
  assert.equal(invalid.status, 400);
  assert.match((await invalid.json() as { error: string }).error, /cycle/);
  const duplicateEdgePlan = { projectId, requirements: [{ key: "a", existingId: a.id, dependsOn: ["b"] }, { key: "b", existingId: b.id }] };
  const duplicateEdge = await json(await api("/plans/drafts", "POST", { plan: duplicateEdgePlan }), 201);
  assert.equal((await api(`/plans/drafts/${duplicateEdge.id}/validate`, "POST", { projectId })).status, 400);
  const invalidAssignee = { projectId, requirements: [{ key: "r", title: "R", tasks: [{ key: "t", title: "T", assignee: randomUUID(), assigneeType: "human" }] }] };
  const assigneeDraft = await json(await api("/plans/drafts", "POST", { plan: invalidAssignee }), 201);
  assert.equal((await api(`/plans/drafts/${assigneeDraft.id}/validate`, "POST", { projectId })).status, 400);
  const duplicateAssignment = { projectId, requirements: [{ key: "r", title: "R", tasks: [{ key: "t", title: "T", slice: "s1" }], slices: [{ key: "s1", title: "First" }, { key: "s2", title: "Second", tasks: ["t"] }] }] };
  const invalidAssignment = await json(await api("/plans/drafts", "POST", { plan: duplicateAssignment }), 201);
  assert.equal((await api(`/plans/drafts/${invalidAssignment.id}/validate`, "POST", { projectId })).status, 400);
  const foreignProject = randomUUID();
  assert.equal((await api("/plans/drafts", "POST", { plan: { projectId, documents: [{ key: "x", projectId: foreignProject, title: "Foreign", content: "x" }] } })).status, 400);
  const ready = await json(await api("/plans/drafts", "POST", { plan }), 201);
  await json(await api(`/plans/drafts/${ready.id}/validate`, "POST", { projectId }));
  await json(await api(`/projects/${projectId}/requirements`, "POST", { title: "Concurrent change" }), 201);
  const operationKey = randomUUID();
  assert.equal((await api(`/plans/drafts/${ready.id}/apply`, "POST", { projectId, revision: 1, operationKey })).status, 409);
  await json(await api(`/plans/drafts/${ready.id}/validate`, "POST", { projectId }));
  const applications = await Promise.all([1, 2].map(() => api(`/plans/drafts/${ready.id}/apply`, "POST", { projectId, revision: 1, operationKey })));
  const receipts = await Promise.all(applications.map(response => json(response)));
  assert.deepEqual(receipts.map(receipt => receipt.replayed).sort(), [false, true]);
  assert.deepEqual(receipts[0].result.refs, receipts[1].result.refs);
  const durable = await json(await api(`/plans/drafts/${ready.id}/receipt?projectId=${projectId}`));
  assert.deepEqual(durable.result.refs, receipts[0].result.refs);
  assert.equal((await api(`/plans/drafts/${ready.id}/receipt?projectId=${projectId}`, "GET", undefined, f.outsider.headers)).status, 404);
  assert.equal((await api(`/plans/drafts/${ready.id}/apply`, "POST", { projectId, revision: 1, operationKey: randomUUID() })).status, 409);
  const createdRequirementId = receipts[0].result.refs.requirements[0].id;
  await json(await api(`/requirements/${createdRequirementId}`, "PATCH", { status: "approved" }));
  await f.identity.setMembership(f.owner.headers, projectId, f.outsider.context.actor.id, { role: "maintainer", explicitPermissions: [] });
  await json(await api(`/requirements/${createdRequirementId}/claim`, "POST", { durationMinutes: 5 }, f.outsider.headers), 201);
  assert.equal((await json(await api(`/plans/drafts/${ready.id}/apply`, "POST", { projectId, revision: 1, operationKey }))).replayed, true);
  await json(await api(`/requirements/${createdRequirementId}/release`, "POST", { reason: "Finish replay test" }, f.outsider.headers));
  await f.identity.removeMembership(f.owner.headers, projectId, f.outsider.context.actor.id);
  const other = await json(await api("/plans/drafts", "POST", { plan }), 201);
  await json(await api(`/plans/drafts/${other.id}/validate`, "POST", { projectId }));
  assert.equal((await api(`/plans/drafts/${other.id}/apply`, "POST", { projectId, revision: 1, operationKey })).status, 409);
  const rollbackPlan = { projectId, documents: [{ key: "doc", title: "Rollback document", content: "test" }], requirements: [{ key: "rollback", title: "Rollback requirement", tasks: [{ key: "failure", title: "Trigger plan failure" }] }] };
  const rollback = await json(await api("/plans/drafts", "POST", { plan: rollbackPlan }), 201);
  await json(await api(`/plans/drafts/${rollback.id}/validate`, "POST", { projectId }));
  await db.execute(sql.raw(`CREATE FUNCTION task_weaver.reject_plan_test() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.title = 'Trigger plan failure' THEN RAISE EXCEPTION 'injected failure'; END IF; RETURN NEW; END $$`));
  await db.execute(sql.raw(`CREATE TRIGGER reject_plan_test BEFORE INSERT ON task_weaver.tasks FOR EACH ROW EXECUTE FUNCTION task_weaver.reject_plan_test()`));
  const rollbackKey = randomUUID();
  assert.equal((await api(`/plans/drafts/${rollback.id}/apply`, "POST", { projectId, revision: 1, operationKey: rollbackKey })).status, 503);
  await db.execute(sql.raw(`DROP TRIGGER reject_plan_test ON task_weaver.tasks`));
  await db.execute(sql.raw(`DROP FUNCTION task_weaver.reject_plan_test()`));
  const noRequirements = await db.select().from(requirements).where(and(eq(requirements.projectId, projectId), eq(requirements.title, "Rollback requirement")));
  assert.equal(noRequirements.length, 0);
  const noDocuments = await db.select().from(documents).where(and(eq(documents.projectId, projectId), eq(documents.title, "Rollback document")));
  assert.equal(noDocuments.length, 0);
  assert.equal((await json(await api(`/plans/drafts/${rollback.id}?projectId=${projectId}`))).state, "draft");
  assert.equal((await json(await api(`/plans/drafts/${rollback.id}/apply`, "POST", { projectId, revision: 1, operationKey: rollbackKey }))).replayed, false);
  const guardedRequirement = await json(await api(`/projects/${projectId}/requirements`, "POST", { title: "Guarded requirement", status: "approved" }), 201);
  const claimedPlan = { projectId, requirements: [{ key: "claimed", existingId: guardedRequirement.id, tasks: [{ key: "guarded", title: "Guarded task" }] }] };
  const guarded = await json(await api("/plans/drafts", "POST", { plan: claimedPlan }), 201);
  await json(await api(`/plans/drafts/${guarded.id}/validate`, "POST", { projectId }));
  await f.identity.setMembership(f.owner.headers, projectId, f.outsider.context.actor.id, { role: "maintainer", explicitPermissions: [] });
  await json(await api(`/requirements/${guardedRequirement.id}/claim`, "POST", { durationMinutes: 5 }, f.outsider.headers), 201);
  const blocked = await api(`/plans/drafts/${guarded.id}/apply`, "POST", { projectId, revision: 1, operationKey: randomUUID() });
  assert.ok([400, 409].includes(blocked.status));
  await json(await api(`/requirements/${guardedRequirement.id}/release`, "POST", { reason: "Finish test" }, f.outsider.headers));
  await f.identity.removeMembership(f.owner.headers, projectId, f.outsider.context.actor.id);
  const expired = await json(await api("/plans/drafts", "POST", { plan }), 201);
  await json(await api(`/plans/drafts/${expired.id}/validate`, "POST", { projectId }));
  await db.update(planDrafts).set({ expiresAt: new Date(0) }).where(eq(planDrafts.id, expired.id));
  assert.equal((await api(`/plans/drafts/${expired.id}?projectId=${projectId}`)).status, 404);
  assert.equal((await api(`/plans/drafts/${expired.id}/apply`, "POST", { projectId, revision: 1, operationKey: randomUUID() })).status, 404);
  await json(await api("/plans/drafts", "POST", { plan }), 201);
  assert.equal((await db.select().from(planDrafts).where(eq(planDrafts.id, expired.id))).length, 0);
  assert.equal((await json(await api(`/plans/drafts/${ready.id}/receipt?projectId=${projectId}`))).revision, 1);
  await json(await api(`/plans/drafts/${draft.id}/discard`, "POST", { projectId, revision: 3 }));
  assert.equal((await api(`/plans/drafts/${draft.id}?projectId=${projectId}`)).status, 404);
});
