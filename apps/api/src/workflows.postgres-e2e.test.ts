import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { createDb, runMigrations, tasks, repositories, requirementRepositories, workflowOutputs } from "@task-weaver/db";
import { join } from "node:path";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resourcePostgresFixture } from "./resource-postgres-fixture";

const databaseUrl = process.env.TW_WORKFLOW_E2E_DATABASE_URL;

test("workflow REST stages, delivery delegations and explicit artifact locality are enforced", { skip: !databaseUrl, timeout: 120_000 }, async (t) => {
  const url = new URL(databaseUrl!);
  assert.equal(url.hostname, "127.0.0.1");
  assert.equal(url.pathname, "/tw_workflow_e2e");
  await runMigrations(databaseUrl!);
  await runMigrations(databaseUrl!);
  const db = createDb(databaseUrl!);
  t.after(() => db.$client.end());
  const fixture = await resourcePostgresFixture(db, databaseUrl!);
  const api = (path: string, method = "GET", body?: unknown, headers = fixture.owner.headers) => fixture.app.request(`/api/v1${path}`, {
    method, headers, body: body === undefined ? undefined : JSON.stringify(body),
  });
  const json = async (response: Response, expected = 200): Promise<any> => {
    assert.equal(response.status, expected, await response.clone().text());
    return response.json();
  };
  const create = async (body: Record<string, unknown>) => json(await api(`/projects/${fixture.project.id}/requirements`, "POST", { title: "Workflow fixture", ...body }), 201);
  const advance = (id: string, data: Record<string, unknown>, headers = fixture.owner.headers) => api(`/requirements/${id}/workflow-advance`, "POST", { reason: "Fixture evidence", ...data }, headers);

  const ordered = await create({});
  assert.equal((await api(`/requirements/${ordered.id}/slices`, "POST", { title: "Retired" })).status, 404);

  const basic = await create({ status: "approved",});
  assert.equal(basic.workflow.delivery.method, "none");
  assert.equal(basic.workflowSource, "basic");
  assert.equal((await json(await advance(basic.id, { stage: "delivery", expectedRevision: 0 }))).status, "done");

  const auto = await create({ status: "approved",});
  const autoTasks = [];
  for (const title of ["First", "Last"]) autoTasks.push(await json(await api(`/projects/${fixture.project.id}/tasks`, "POST", { requirementId: auto.id, title }), 201));
  await json(await api(`/tasks/${autoTasks[0].id}/status`, "PATCH", { status: "done" }));
  assert.notEqual((await json(await api(`/requirements/${auto.id}`))).status, "done");
  await json(await api(`/tasks/${autoTasks[1].id}/status`, "PATCH", { status: "cancelled" }));
  const autoDone = await json(await api(`/requirements/${auto.id}`));
  assert.equal(autoDone.status, "done");
  assert.equal(autoDone.workflowState.acceptance, "skipped");
  await json(await api(`/tasks/${autoTasks[0].id}/status`, "PATCH", { status: "done" }));
  assert.equal((await json(await api(`/requirements/${auto.id}`))).workflowStateRevision, autoDone.workflowStateRevision);
  const draft = await create({ status: "draft" });
  assert.equal((await advance(draft.id, { stage: "delivery", expectedRevision: 0 })).status, 400);
  const draftTask = await json(await api(`/projects/${fixture.project.id}/tasks`, "POST", { requirementId: draft.id, title: "Draft task" }), 201);
  await json(await api(`/tasks/${draftTask.id}/status`, "PATCH", { status: "done" }));
  assert.equal((await json(await api(`/requirements/${draft.id}`))).status, "draft");
  const gated = await create({ status: "approved", workflow: { delivery: { mode: "automatic", method: "none" }, acceptance: { mode: "manual", minimumHumanApprovals: 1 }, integration: { mode: "manual", method: "none" } } });
  const gatedTask = await json(await api(`/projects/${fixture.project.id}/tasks`, "POST", { requirementId: gated.id, title: "Needs human review" }), 201);
  await json(await api(`/tasks/${gatedTask.id}/status`, "PATCH", { status: "done" }));
  const gatedState = await json(await api(`/requirements/${gated.id}`));
  assert.equal(gatedState.status, "in_review");
  assert.equal(gatedState.workflowState.acceptance, "pending");
  assert.equal(gatedState.workflowState.integration, "pending");

  const projectDefault = { delivery: { method: "url" }, acceptance: {}, integration: {} };
  await json(await api(`/projects/${fixture.project.id}`, "PATCH", { defaultWorkflow: projectDefault }));
  const inherited = await create({});
  assert.equal(inherited.workflowSource, "project");
  assert.equal(inherited.workflow.delivery.method, "url");
  const batch = await json(await api("/requirements/batch", "POST", { requirements: [{ projectId: fixture.project.id, title: "Batch default" }] }), 201);
  assert.equal(batch[0].workflowSource, "project");
  const plan = { projectId: fixture.project.id, requirements: [{ key: "inherited", title: "Plan default" }, { key: "explicit", title: "Plan override", workflowPreset: "comment" }] };
  const preview = await json(await api("/plans/apply", "POST", { dryRun: true, plan }));
  assert.equal(preview.workflows[0].workflow.delivery.method, "url");
  assert.equal(preview.workflows[1].workflow.delivery.method, "comment");
  const applied = await json(await api("/plans/apply", "POST", { plan }), 201);
  const planned = await json(await api(`/requirements/${applied.refs.requirements[1].id}`));
  assert.equal(planned.workflow.delivery.method, "comment");
  assert.equal((await api("/plans/apply", "POST", { dryRun: true, plan }, fixture.outsider.headers)).status, 404);
  await json(await api(`/projects/${fixture.project.id}`, "PATCH", { defaultWorkflow: null }));

  const manual = await create({ status: "approved", workflow: { delivery: { method: "url" }, acceptance: { mode: "manual", requiredChecks: ["Complete report"], minimumHumanApprovals: 1 }, integration: {} } });
  assert.equal((await advance(manual.id, { stage: "delivery", expectedRevision: 0 })).status, 400);
  const output = await json(await api(`/requirements/${manual.id}/workflow-outputs`, "POST", { type: "url", url: "https://example.test/report" }), 201);
  assert.equal(output.workflowRevision, 1);
  assert.equal((await advance(manual.id, { stage: "delivery", expectedRevision: 0 })).status, 409);
  assert.equal((await api(`/requirements/${manual.id}/workflow-outputs`, "GET", undefined, fixture.outsider.headers)).status, 404);
  assert.equal((await json(await advance(manual.id, { stage: "delivery", expectedRevision: 1 }))).status, "in_review");
  assert.equal((await advance(manual.id, { stage: "acceptance", expectedRevision: 2 })).status, 400);
  const rework = await json(await advance(manual.id, { stage: "acceptance", decision: "changes_requested", expectedRevision: 2 }));
  assert.equal(rework.status, "in_progress");
  const followups = await db.query.tasks.findMany({ where: eq(tasks.requirementId, manual.id) });
  assert.equal(followups.length, 1);
  await db.update(tasks).set({ status: "done" }).where(eq(tasks.id, followups[0]!.id));
  const failedResubmission = await json(await advance(manual.id, { stage: "delivery", decision: "failed", expectedRevision: 3 }));
  assert.equal(failedResubmission.workflowState.delivery, "failed");
  assert.equal(failedResubmission.workflowState.acceptance, "failed");
  await json(await advance(manual.id, { stage: "delivery", decision: "retry", expectedRevision: 4 }));
  const resubmitted = await json(await advance(manual.id, { stage: "delivery", expectedRevision: 5 }));
  assert.equal(resubmitted.status, "in_review");
  assert.equal(resubmitted.workflowState.acceptance, "pending");
  assert.equal((await json(await advance(manual.id, { stage: "acceptance", expectedRevision: 6, checks: [{ name: "Complete report", status: "passed" }] }))).status, "done");

  const agent = await fixture.identity.createAgent(fixture.owner.headers, { displayName: "Workflow executor" });
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, agent.id, { role: "maintainer", explicitPermissions: [] });
  const key = await fixture.identity.issueKey(fixture.owner.headers, agent.id, { name: "Workflow fixture", expiresAt: null, grants: [{ scope: "project", projectId: fixture.project.id, permissions: ["resource.read", "resource.write", "execution.run", "audit.read"] }] });
  const agentHeaders = new Headers({ authorization: `Bearer ${key.rawKey}`, "content-type": "application/json" });
  assert.equal((await api("/daemons/register", "POST", { id: randomUUID() }, agentHeaders)).status, 404);
  const content = Buffer.from("historical artifact bytes");
  const { createHash } = await import("node:crypto");
  const contentHash = createHash("sha256").update(content).digest("hex");
  const boundRequirement = await create({ workflowPreset: "local" });
  const boundOutput = await json(await api(`/requirements/${boundRequirement.id}/workflow-outputs`, "POST", { type: "local", nodeId: "old-node", relativePath: `${boundRequirement.id}/bound.txt`, sizeBytes: content.length, sha256: contentHash }), 201);
  const storageDir = await mkdtemp(join(tmpdir(), "tw-promotion-"));
  const previousStorage = process.env.TW_ATTACHMENT_STORAGE_DIR; process.env.TW_ATTACHMENT_STORAGE_DIR = storageDir;
  t.after(async () => { if (previousStorage === undefined) delete process.env.TW_ATTACHMENT_STORAGE_DIR; else process.env.TW_ATTACHMENT_STORAGE_DIR = previousStorage; await rm(storageDir, { recursive: true, force: true }); });
  const importPath = `/requirements/${boundRequirement.id}/workflow-outputs/${boundOutput.id}/import`;
  const upload = (data: Buffer, headers: Headers) => { const h = new Headers(headers); h.set("content-type", "application/octet-stream"); return fixture.app.request(`/api/v1${importPath}`, { method: "POST", headers: h, body: Uint8Array.from(data) }); };
  assert.notEqual((await upload(content, fixture.outsider.headers)).status, 200);
  assert.equal((await upload(content, agentHeaders)).status, 403);
  assert.notEqual((await upload(Buffer.from("wrong content"), fixture.owner.headers)).status, 200);
  const promoted = await json(await upload(content, fixture.owner.headers));
  assert.equal(promoted.replayed, false);
  assert.equal((await json(await upload(content, fixture.owner.headers))).replayed, true);
  const metadata = await json(await api(`/requirements/${boundRequirement.id}/workflow-outputs/${boundOutput.id}/evidence`));
  assert.equal(metadata.availability, "available");
  assert.equal(metadata.kind, "attachment");

  const [gitRepo] = await db.insert(repositories).values({ displayName: "Git evidence fixture", provider: "github", host: "github.com", namespace: "acme", name: `fixture-${randomUUID()}`, canonicalKey: `fixture-${randomUUID()}`, createdBy: fixture.owner.context.actor.id }).returning();
  const [gitLink] = await db.insert(requirementRepositories).values({ requirementId: boundRequirement.id, repositoryId: gitRepo!.id, baseBranch: "main" }).returning();
  const head = "b".repeat(40), base = "a".repeat(40), mergeBase = "c".repeat(40);
  const [gitOutput] = await db.insert(workflowOutputs).values({ requirementId: boundRequirement.id, requirementRepositoryId: gitLink!.id, type: "git_branch", headCommit: head, createdBy: fixture.owner.context.actor.id, createdByType: "human" }).returning();
  const { createGitEvidenceService } = await import("@task-weaver/core");
  let branchTip = base;
  const forgeFetch: typeof fetch = async url => {
    if (String(url).endsWith("/branches/main")) return Response.json({ name: "main", commit: { sha: branchTip } });
    assert.ok(String(url).endsWith(`/compare/${base}...${head}`));
    return Response.json({ base_commit: { sha: base }, merge_base_commit: { sha: mergeBase }, files: [{ filename: "src/example.ts", status: "modified", patch: "+example" }] });
  };
  const comparison = await createGitEvidenceService(fixture.owner.context, { fetch: forgeFetch }).compare(db, boundRequirement.id, gitOutput!.id, "current");
  assert.equal(comparison.headCommit, head); assert.equal("patch" in comparison.files[0]!, false);
  assert.equal((await createGitEvidenceService(fixture.owner.context, { fetch: forgeFetch }).compare(db, boundRequirement.id, gitOutput!.id, "current")).comparisonId, comparison.comparisonId);
  await assert.rejects(createGitEvidenceService(fixture.owner.context, { fetch: forgeFetch }).compare(db, boundRequirement.id, gitOutput!.id), /no trusted historical/);
  await db.update(workflowOutputs).set({ gitBaseline: { baseCommit: base, headCommit: head, comparisonCommit: mergeBase, repositoryKey: JSON.stringify([gitRepo!.provider, gitRepo!.host, gitRepo!.namespace, gitRepo!.name]), capturedAt: new Date().toISOString() } }).where(eq(workflowOutputs.id, gitOutput!.id));
  branchTip = "d".repeat(40);
  assert.equal((await createGitEvidenceService(fixture.owner.context, { fetch: forgeFetch }).compare(db, boundRequirement.id, gitOutput!.id)).baseCommit, base);
  assert.equal((await createGitEvidenceService(fixture.owner.context, { fetch: forgeFetch }).file(db, boundRequirement.id, gitOutput!.id, comparison.comparisonId, "src/example.ts")).patch, "+example");
  await assert.rejects(createGitEvidenceService(fixture.outsider.context, { fetch: async () => { throw new Error("Unauthorized forge fetch"); } }).compare(db, boundRequirement.id, gitOutput!.id, "current"));
  await assert.rejects(createGitEvidenceService(fixture.outsider.context, { fetch: async () => { throw new Error("Unauthorized forge fetch"); } }).file(db, boundRequirement.id, gitOutput!.id, comparison.comparisonId, "src/example.ts"));
  assert.notEqual((await api(`/requirements/${boundRequirement.id}/workflow-outputs/${gitOutput!.id}/git-comparison`, "POST", {}, fixture.outsider.headers)).status, 200);
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id, { role: "viewer", explicitPermissions: [] });
  branchTip = base;
  assert.equal((await createGitEvidenceService(fixture.outsider.context, { fetch: forgeFetch }).file(db, boundRequirement.id, gitOutput!.id, comparison.comparisonId, "src/example.ts")).patch, "+example");
  let forgeRequests = 0;
  await assert.rejects(createGitEvidenceService(fixture.outsider.context, { fetch: async url => {
    forgeRequests++;
    if (forgeRequests === 3) await fixture.identity.removeMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id);
    return forgeFetch(url);
  } }).compare(db, boundRequirement.id, gitOutput!.id, "current"));
  assert.equal(forgeRequests, 3);
  await assert.rejects(createGitEvidenceService(fixture.outsider.context, { fetch: forgeFetch }).file(db, boundRequirement.id, gitOutput!.id, comparison.comparisonId, "src/example.ts"));
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id, { role: "viewer", explicitPermissions: [] });
  await assert.rejects(createGitEvidenceService(fixture.outsider.context, { fetch: async url => {
    await fixture.identity.removeMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id);
    return forgeFetch(url);
  } }).file(db, boundRequirement.id, gitOutput!.id, comparison.comparisonId, "src/example.ts"));
  const producer = await create({ status: "approved", workflowPreset: "local" });
  const local = await json(await api(`/requirements/${producer.id}/workflow-outputs`, "POST", { type: "local", nodeId: "node-a", relativePath: `${producer.id}/file.bin`, sizeBytes: 42, sha256: "a".repeat(64) }), 201);
  const evidence = await json(await api(`/requirements/${producer.id}/workflow-outputs/${local.id}/evidence`));
  assert.equal(evidence.kind, "local");
  assert.equal(evidence.availability, "unsupported");
  assert.equal(evidence.sha256, "a".repeat(64));
  assert.equal("relativePath" in evidence, false);
  assert.equal((await api(`/requirements/${producer.id}/workflow-outputs/${local.id}/evidence`, "GET", undefined, fixture.outsider.headers)).status, 404);
  await json(await advance(producer.id, { stage: "delivery", expectedRevision: 1 }));
  const consumer = await create({ status: "approved" });
  const task = await json(await api(`/projects/${fixture.project.id}/tasks`, "POST", { requirementId: consumer.id, title: "Consume local output" }), 201);
  await json(await api(`/requirements/${consumer.id}/workflow-inputs`, "POST", { outputId: local.id, taskId: task.id }), 201);
  assert.equal((await api(`/requirements/${producer.id}/workflow-output-retire`, "POST", { outputId: local.id })).status, 400);
  const cleanup = await json(await api(`/requirements/${producer.id}/workflow-cleanup`));
  assert.equal(cleanup.canCleanupWorktrees, false);
  assert.equal(cleanup.activeConsumers, 1);
  assert.equal((await api(`/daemons/${randomUUID()}/apply-requirement`, "POST", { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders)).status, 404);

});
