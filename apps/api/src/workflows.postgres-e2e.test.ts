import assert from "node:assert/strict";
import test from "node:test";
import { randomUUID, generateKeyPairSync, sign } from "node:crypto";
import { evidenceRegistrationPayload, evidenceDemandPayload } from "@task-weaver/contracts";
import { eq } from "drizzle-orm";
import { createDb, runMigrations, tasks } from "@task-weaver/db";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createApiApplication } from "./application";
import { resourcePostgresFixture } from "./resource-postgres-fixture";

const databaseUrl = process.env.TW_WORKFLOW_E2E_DATABASE_URL;

test("workflow REST stages, delivery delegations and explicit artifact locality are enforced", { skip: !databaseUrl, timeout: 120_000 }, async (t) => {
  const url = new URL(databaseUrl!);
  assert.equal(url.hostname, "127.0.0.1");
  assert.equal(url.pathname, "/tw_workflow_e2e");
  await runMigrations(databaseUrl!);
  await runMigrations(databaseUrl!);
  const db = createDb(databaseUrl!);
  t.after(() => db.$client.end());
  const fixture = await resourcePostgresFixture(db, databaseUrl!);
  const api = (path: string, method = "GET", body?: unknown, headers = fixture.owner.headers) => fixture.app.request(`/api/v1${path}`, {
    method, headers, body: body === undefined ? undefined : JSON.stringify(body),
  });
  const json = async (response: Response, expected = 200): Promise<any> => {
    assert.equal(response.status, expected, await response.clone().text());
    return response.json();
  };
  const create = async (body: Record<string, unknown>) => json(await api(`/projects/${fixture.project.id}/requirements`, "POST", { title: "Workflow fixture", ...body }), 201);
  const advance = (id: string, data: Record<string, unknown>, headers = fixture.owner.headers) => api(`/requirements/${id}/workflow-advance`, "POST", { reason: "Fixture evidence", ...data }, headers);

  const basic = await create({});
  assert.equal(basic.workflow.delivery.method, "none");
  assert.equal(basic.workflowSource, "basic");
  assert.equal((await json(await advance(basic.id, { stage: "delivery", expectedRevision: 0 }))).status, "done");

  const projectDefault = { delivery: { method: "url" }, acceptance: {}, integration: {} };
  await json(await api(`/projects/${fixture.project.id}`, "PATCH", { defaultWorkflow: projectDefault }));
  const inherited = await create({});
  assert.equal(inherited.workflowSource, "project");
  assert.equal(inherited.workflow.delivery.method, "url");
  const batch = await json(await api("/requirements/batch", "POST", { requirements: [{ projectId: fixture.project.id, title: "Batch default" }] }), 201);
  assert.equal(batch[0].workflowSource, "project");
  const plan = { projectId: fixture.project.id, requirements: [{ key: "inherited", title: "Plan default" }, { key: "explicit", title: "Plan override", workflowPreset: "comment" }] };
  const preview = await json(await api("/plans/apply", "POST", { dryRun: true, plan }));
  assert.equal(preview.workflows[0].workflow.delivery.method, "url");
  assert.equal(preview.workflows[1].workflow.delivery.method, "comment");
  const applied = await json(await api("/plans/apply", "POST", { plan }), 201);
  const planned = await json(await api(`/requirements/${applied.refs.requirements[1].id}`));
  assert.equal(planned.workflow.delivery.method, "comment");
  assert.equal((await api("/plans/apply", "POST", { dryRun: true, plan }, fixture.outsider.headers)).status, 404);
  await json(await api(`/projects/${fixture.project.id}`, "PATCH", { defaultWorkflow: null }));

  const manual = await create({ workflow: { delivery: { method: "url" }, acceptance: { mode: "manual", requiredChecks: ["Complete report"], minimumHumanApprovals: 1 }, integration: {} } });
  assert.equal((await advance(manual.id, { stage: "delivery", expectedRevision: 0 })).status, 400);
  const output = await json(await api(`/requirements/${manual.id}/workflow-outputs`, "POST", { type: "url", url: "https://example.test/report" }), 201);
  assert.equal(output.workflowRevision, 1);
  assert.equal((await advance(manual.id, { stage: "delivery", expectedRevision: 0 })).status, 409);
  assert.equal((await api(`/requirements/${manual.id}/workflow-outputs`, "GET", undefined, fixture.outsider.headers)).status, 404);
  assert.equal((await json(await advance(manual.id, { stage: "delivery", expectedRevision: 1 }))).status, "in_review");
  assert.equal((await advance(manual.id, { stage: "acceptance", expectedRevision: 2 })).status, 400);
  const rework = await json(await advance(manual.id, { stage: "acceptance", decision: "changes_requested", expectedRevision: 2 }));
  assert.equal(rework.status, "in_progress");
  const followups = await db.query.tasks.findMany({ where: eq(tasks.requirementId, manual.id) });
  assert.equal(followups.length, 1);
  await db.update(tasks).set({ status: "done" }).where(eq(tasks.id, followups[0]!.id));
  const failedResubmission = await json(await advance(manual.id, { stage: "delivery", decision: "failed", expectedRevision: 3 }));
  assert.equal(failedResubmission.workflowState.delivery, "failed");
  assert.equal(failedResubmission.workflowState.acceptance, "failed");
  await json(await advance(manual.id, { stage: "delivery", decision: "retry", expectedRevision: 4 }));
  const resubmitted = await json(await advance(manual.id, { stage: "delivery", expectedRevision: 5 }));
  assert.equal(resubmitted.status, "in_review");
  assert.equal(resubmitted.workflowState.acceptance, "pending");
  assert.equal((await json(await advance(manual.id, { stage: "acceptance", expectedRevision: 6, checks: [{ name: "Complete report", status: "passed" }] }))).status, "done");

  const agent = await fixture.identity.createAgent(fixture.owner.headers, { displayName: "Workflow executor" });
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, agent.id, { role: "maintainer", explicitPermissions: [] });
  const key = await fixture.identity.issueKey(fixture.owner.headers, agent.id, { name: "Workflow fixture", expiresAt: null, grants: [{ scope: "project", projectId: fixture.project.id, permissions: ["resource.read", "resource.write", "execution.run", "audit.read"] }] });
  const agentHeaders = new Headers({ authorization: `Bearer ${key.rawKey}`, "content-type": "application/json" });
  const daemonA = randomUUID(), daemonB = randomUUID();
  for (const [id, nodeId] of [[daemonA, "node-a"], [daemonB, "node-b"]]) await json(await api("/daemons/register", "POST", { id, name: "Workflow fixture", nodeId, capabilities: ["codex", "executor:codex", "workflow-agent", "live-plan-v1"], role: "executor" }, agentHeaders), 201);

  const delivery = await create({ status: "approved", workflowPreset: "url" });
  const lane = await json(await api(`/daemons/${daemonA}/apply-requirement`, "POST", { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders));
  assert.equal(lane.requirement.id, delivery.id);
  assert.equal(lane.stage, "delivery");
  assert.equal(lane.task, null);
  const capability = await json(await api(`/daemons/${daemonA}/delegations`, "POST", { requirementId: delivery.id, runId: lane.runId, leaseGeneration: lane.leaseGeneration, workerIndex: 0 }, agentHeaders), 201);
  assert.equal(capability.delegation.purpose, "delivery");
  assert.deepEqual(capability.delegation.taskIds, []);
  const delegated = new Headers({ authorization: `Bearer ${capability.token}`, "content-type": "application/json" });
  await json(await api(`/requirements/${delivery.id}/workflow-outputs`, "POST", { type: "url", url: "https://example.test/delivery" }, delegated), 201);
  assert.equal((await advance(delivery.id, { stage: "delivery", expectedRevision: 1 }, delegated)).status, 403);
  const delivered = await json(await advance(delivery.id, { stage: "delivery", expectedRevision: 1, daemonId: daemonA, runId: lane.runId, leaseGeneration: lane.leaseGeneration }, agentHeaders));
  assert.equal(delivered.status, "done");
  assert.equal((await api("/auth/me", "GET", undefined, delegated)).status, 401);

  const signedProducer = await create({ workflowPreset: "local" });
  const pair = generateKeyPairSync("ed25519");
  const nodePublicKey = pair.publicKey.export({ type: "spki", format: "der" }).toString("base64");
  const manifest = { requirementId: signedProducer.id, nodeId: "signed-node", relativePath: `${signedProducer.id}/result.txt`, sizeBytes: 5, sha256: "b".repeat(64) };
  const nodeRegistrationProof = sign(null, Buffer.from(evidenceRegistrationPayload(manifest)), pair.privateKey).toString("base64");
  const signed = { type: "local", ...manifest, nodePublicKey, nodeRegistrationProof };
  assert.equal((await api(`/requirements/${signedProducer.id}/workflow-outputs`, "POST", { ...signed, sha256: "c".repeat(64) })).status, 400);
  const signedOutput = await json(await api(`/requirements/${signedProducer.id}/workflow-outputs`, "POST", signed), 201);
  assert.equal(signedOutput.nodePublicKey, nodePublicKey);
  const { EvidenceSessionService } = await import(pathToFileURL(resolve("../../packages/core/src/services/evidence-session.ts")).href);
  const evidenceDaemon = randomUUID();
  await json(await api("/daemons/register", "POST", { id: evidenceDaemon, name: "Evidence fixture", nodeId: "bound-node", capabilities: ["codex", "executor:codex", "live-plan-v1", "evidence-read-v1"], role: "executor" }, agentHeaders), 201);
  const content = Buffer.from("bound bytes");
  const { createHash } = await import("node:crypto");
  const contentHash = createHash("sha256").update(content).digest("hex");
  const boundRequirement = await create({ workflowPreset: "local" });
  const boundManifest = { requirementId: boundRequirement.id, nodeId: "bound-node", relativePath: `${boundRequirement.id}/bound`, sizeBytes: content.length, sha256: contentHash };
  const boundProof = sign(null, Buffer.from(evidenceRegistrationPayload(boundManifest)), pair.privateKey).toString("base64");
  const boundOutput = await json(await api(`/requirements/${boundRequirement.id}/workflow-outputs`, "POST", { type: "local", ...boundManifest, nodePublicKey, nodeRegistrationProof: boundProof }, agentHeaders), 201);
  const broker = new EvidenceSessionService(db); t.after(() => broker.close());
  const agentContext = await fixture.auth.resolve(agentHeaders);
  const session = await broker.open(fixture.owner.context, boundRequirement.id, boundOutput.id, "download");
  assert.deepEqual(await broker.poll(agentContext, daemonB), []);
  const [demand] = await broker.poll(agentContext, evidenceDaemon); assert.ok(demand);
  assert.equal("relativePath" in demand, false);
  const challengeProof = sign(null, Buffer.from(evidenceDemandPayload(demand)), pair.privateKey).toString("base64");
  await assert.rejects(broker.claim(agentContext, evidenceDaemon, session.requestId, "invalid"));
  const accepted = await broker.claim(agentContext, evidenceDaemon, session.requestId, challengeProof);
  assert.equal(accepted.relativePath, boundManifest.relativePath);
  await assert.rejects(broker.claim(agentContext, evidenceDaemon, session.requestId, challengeProof));
  await broker.push(agentContext, evidenceDaemon, session.requestId, 0, content);
  await broker.finish(agentContext, evidenceDaemon, session.requestId, 1);
  const chunks: Buffer[] = [];
  for await (const chunk of broker.read(fixture.owner.context, session.requestId)) chunks.push(chunk);
  assert.deepEqual(Buffer.concat(chunks), content);
  const transport = createApiApplication({ db, databaseUrl: databaseUrl!, env: { TW_AUTH_SECRET: fixture.configuration.secret, TW_AUTH_BASE_URL: fixture.configuration.baseURL, TW_AUTH_TRUSTED_ORIGINS: fixture.configuration.trustedOrigins[0], TW_PRESET_SKILLS_SYNC: "disabled", TW_EVIDENCE_READ_ENABLED: "true" } });
  t.after(() => transport.stop());
  const evidenceApi = (path: string, method = "GET", body?: unknown, headers = fixture.owner.headers) => transport.app.request(`/api/v1/evidence${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const remote = await json(await evidenceApi("/open", "POST", { requirementId: boundRequirement.id, outputId: boundOutput.id, purpose: "download" }), 201);
  assert.equal((await json(await evidenceApi(`/demands/${daemonB}`, "GET", undefined, agentHeaders))).items.length, 0);
  const remoteDemand = (await json(await evidenceApi(`/demands/${evidenceDaemon}`, "GET", undefined, agentHeaders))).items[0];
  const remoteProof = sign(null, Buffer.from(evidenceDemandPayload(remoteDemand)), pair.privateKey).toString("base64");
  assert.equal((await evidenceApi(`/${remote.requestId}/claim`, "POST", { daemonId: daemonB, signature: remoteProof }, agentHeaders)).status, 400);
  assert.equal((await json(await evidenceApi(`/${remote.requestId}/claim`, "POST", { daemonId: evidenceDaemon, signature: remoteProof }, agentHeaders))).relativePath, boundManifest.relativePath);
  await json(await evidenceApi(`/${remote.requestId}/chunk`, "POST", { daemonId: evidenceDaemon, sequence: 0, contentBase64: content.toString("base64") }, agentHeaders));
  await json(await evidenceApi(`/${remote.requestId}/finish`, "POST", { daemonId: evidenceDaemon, sequence: 1 }, agentHeaders));
  const download = await evidenceApi(`/${remote.requestId}/content`);
  assert.equal(download.status, 200); assert.equal(download.headers.get("x-content-type-options"), "nosniff");
  assert.deepEqual(Buffer.from(await download.arrayBuffer()), content);
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id, { role: "viewer", explicitPermissions: [] });
  const failedSession = await json(await evidenceApi("/open", "POST", { requirementId: boundRequirement.id, outputId: boundOutput.id, purpose: "download" }), 201);
  const failedDemand = (await json(await evidenceApi(`/demands/${evidenceDaemon}`, "GET", undefined, agentHeaders))).items.find((item: { requestId: string }) => item.requestId === failedSession.requestId);
  const failedProof = sign(null, Buffer.from(evidenceDemandPayload(failedDemand)), pair.privateKey).toString("base64");
  await json(await evidenceApi(`/${failedSession.requestId}/claim`, "POST", { daemonId: evidenceDaemon, signature: failedProof }, agentHeaders));
  await json(await evidenceApi(`/${failedSession.requestId}/fail`, "POST", { daemonId: evidenceDaemon, state: "changed" }, agentHeaders));
  const failedStatus = await json(await evidenceApi(`/${failedSession.requestId}/status`));
  assert.equal(failedStatus.state, "failed"); assert.equal(failedStatus.failure, "changed");
  assert.equal((await evidenceApi(`/${failedSession.requestId}/content`)).status, 409);
  await json(await evidenceApi(`/${failedSession.requestId}/cancel`, "POST", {}));
  const revokedSession = await json(await evidenceApi("/open", "POST", { requirementId: boundRequirement.id, outputId: boundOutput.id, purpose: "download" }, fixture.outsider.headers), 201);
  const revokedDemand = (await json(await evidenceApi(`/demands/${evidenceDaemon}`, "GET", undefined, agentHeaders))).items.find((item: { requestId: string }) => item.requestId === revokedSession.requestId);
  const revokedProof = sign(null, Buffer.from(evidenceDemandPayload(revokedDemand)), pair.privateKey).toString("base64");
  await json(await evidenceApi(`/${revokedSession.requestId}/claim`, "POST", { daemonId: evidenceDaemon, signature: revokedProof }, agentHeaders));
  await fixture.identity.removeMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id);
  assert.notEqual((await evidenceApi(`/${revokedSession.requestId}/chunk`, "POST", { daemonId: evidenceDaemon, sequence: 0, contentBase64: content.toString("base64") }, agentHeaders)).status, 200);
  assert.notEqual((await evidenceApi(`/${revokedSession.requestId}/content`, "GET", undefined, fixture.outsider.headers)).status, 200);
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id, { role: "viewer", explicitPermissions: [] });
  await broker.open(fixture.outsider.context, boundRequirement.id, boundOutput.id, "preview");
  await fixture.identity.removeMembership(fixture.owner.headers, fixture.project.id, fixture.outsider.context.actor.id);
  assert.deepEqual(await broker.poll(agentContext, evidenceDaemon), []);
  const producer = await create({ workflowPreset: "local" });
  const local = await json(await api(`/requirements/${producer.id}/workflow-outputs`, "POST", { type: "local", nodeId: "node-a", relativePath: `${producer.id}/file.bin`, sizeBytes: 42, sha256: "a".repeat(64) }), 201);
  const evidence = await json(await api(`/requirements/${producer.id}/workflow-outputs/${local.id}/evidence`));
  assert.equal(evidence.kind, "local");
  assert.equal(evidence.availability, "unsupported");
  assert.equal(evidence.sha256, "a".repeat(64));
  assert.equal("relativePath" in evidence, false);
  assert.equal((await api(`/requirements/${producer.id}/workflow-outputs/${local.id}/evidence`, "GET", undefined, fixture.outsider.headers)).status, 404);
  await json(await advance(producer.id, { stage: "delivery", expectedRevision: 1 }));
  const consumer = await create({ status: "approved" });
  const task = await json(await api(`/projects/${fixture.project.id}/tasks`, "POST", { requirementId: consumer.id, title: "Consume local output" }), 201);
  await json(await api(`/requirements/${consumer.id}/workflow-inputs`, "POST", { outputId: local.id, taskId: task.id }), 201);
  assert.equal((await api(`/requirements/${producer.id}/workflow-output-retire`, "POST", { outputId: local.id })).status, 400);
  const cleanup = await json(await api(`/requirements/${producer.id}/workflow-cleanup`));
  assert.equal(cleanup.canCleanupWorktrees, false);
  assert.equal(cleanup.activeConsumers, 1);
  const wrongNode = await json(await api(`/daemons/${daemonB}/apply-requirement`, "POST", { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders));
  assert.equal(wrongNode.requirement, null);
  const rightNode = await json(await api(`/daemons/${daemonA}/apply-requirement`, "POST", { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders));
  assert.equal(rightNode.task.id, task.id);
  await json(await api(`/requirements/${consumer.id}/release`, "POST", { daemonId: daemonA, leaseGeneration: rightNode.leaseGeneration }, agentHeaders));
  await db.update(tasks).set({ status: "todo" }).where(eq(tasks.id, task.id));
  assert.equal((await api(`/requirements/${producer.id}/workflow-output-availability`, "POST", { outputId: local.id, nodeId: "node-a", daemonId: daemonB, availability: "available", reason: "Wrong node" }, agentHeaders)).status, 400);
  await json(await api(`/requirements/${producer.id}/workflow-output-availability`, "POST", { outputId: local.id, nodeId: "node-a", daemonId: daemonA, availability: "missing", reason: "File removed" }, agentHeaders));
  assert.equal((await json(await api(`/daemons/${daemonA}/apply-requirement`, "POST", { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders))).requirement, null);
});
