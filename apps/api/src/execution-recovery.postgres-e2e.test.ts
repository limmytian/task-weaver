import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { eq } from 'drizzle-orm';
import { createDb, runMigrations, requirementClaims, executionControls, requirements, daemons, taskClaims } from '@task-weaver/db';
import { resourcePostgresFixture } from './resource-postgres-fixture';

const databaseUrl = process.env.TW_EXECUTION_RECOVERY_E2E_DATABASE_URL;
test('live planning fences old runs, preserves healthy leases and releases dependency waiting capacity', { skip: !databaseUrl, timeout: 120_000 }, async t => {
  const url = new URL(databaseUrl!);
  assert.equal(url.hostname, '127.0.0.1');
  assert.equal(url.pathname, '/tw_execution_recovery_e2e');
  await runMigrations(databaseUrl!);
  await runMigrations(databaseUrl!);
  const db = createDb(databaseUrl!);
  t.after(() => db.$client.end());
  const fixture = await resourcePostgresFixture(db, databaseUrl!);
  const api = (path: string, method = 'GET', body?: unknown, headers = fixture.owner.headers) => fixture.app.request(`/api/v1${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const json = async (response: Response, expected = 200): Promise<any> => { assert.equal(response.status, expected, await response.clone().text()); return response.json(); };
  const agent = await fixture.identity.createAgent(fixture.owner.headers, { displayName: 'Recovery executor' });
  await fixture.identity.setMembership(fixture.owner.headers, fixture.project.id, agent.id, { role: 'maintainer', explicitPermissions: [] });
  const key = await fixture.identity.issueKey(fixture.owner.headers, agent.id, { name: 'Recovery test', expiresAt: null, grants: [{ scope: 'project', projectId: fixture.project.id, permissions: ['resource.read', 'resource.write', 'execution.run', 'audit.read'] }, { scope: 'personal', actorId: fixture.owner.context.actor.id, permissions: ['resource.read'] }] });
  const agentHeaders = new Headers({ authorization: `Bearer ${key.rawKey}`, 'content-type': 'application/json' });
  const daemonA = randomUUID(), daemonB = randomUUID();
  for (const [id, nodeId] of [[daemonA, 'node-a'], [daemonB, 'node-b']]) await json(await api('/daemons/register', 'POST', { id, nodeId, name: 'Recovery fixture', role: 'executor', capabilities: ['codex', 'executor:codex', 'live-plan-v1'] }, agentHeaders), 201);
  const create = async (title: string, policy?: unknown) => json(await api(`/projects/${fixture.project.id}/requirements`, 'POST', { title, status: 'approved', recoveryPolicy: policy }), 201);
  const task = async (requirementId: string, title: string) => json(await api(`/projects/${fixture.project.id}/tasks`, 'POST', { requirementId, title }), 201);
  const acquire = (daemon = daemonA) => api(`/daemons/${daemon}/apply-requirement`, 'POST', { projectId: fixture.project.id, workerIndex: 0 }, agentHeaders);
  const requirement = await create('Plan reconciliation');
  const activeTask = await task(requirement.id, 'Work under current plan');
  const lane = await json(await acquire());
  assert.equal(lane.task.id, activeTask.id);
  const fence = { daemonId: daemonA, leaseGeneration: lane.leaseGeneration, runId: lane.runId };
  const capability = await json(await api(`/daemons/${daemonA}/delegations`, 'POST', { requirementId: requirement.id, taskId: activeTask.id, workerIndex: 0, runId: lane.runId, leaseGeneration: lane.leaseGeneration }, agentHeaders), 201);
  const child = new Headers({ authorization: `Bearer ${capability.token}`, 'content-type': 'application/json' });
  await json(await api(`/tasks/${activeTask.id}`, 'PATCH', { priority: 'high' }));
  assert.equal((await api('/auth/me', 'GET', undefined, child)).status, 200);
  await json(await api(`/tasks/${activeTask.id}`, 'PATCH', { description: 'New acceptance criteria' }));
  assert.equal((await api('/auth/me', 'GET', undefined, child)).status, 401);
  assert.notEqual((await api(`/tasks/${activeTask.id}/status`, 'PATCH', { status: 'done', ...fence }, agentHeaders)).status, 200);
  await json(await api(`/requirements/${requirement.id}/heartbeat`, 'POST', { extendMinutes: 2, ...fence }, agentHeaders));
  assert.equal((await db.query.requirementClaims.findFirst({ where: eq(requirementClaims.requirementId, requirement.id) }))!.id, lane.runId);
  const controls = async () => (await json(await api(`/daemons/${daemonA}/execution-controls`, 'GET', undefined, agentHeaders))).items as any[];
  let control = (await controls()).find(row => row.runId === lane.runId);
  const deadline = control.deadline;
  await json(await api(`/tasks/${activeTask.id}`, 'PATCH', { description: 'Latest acceptance criteria' }));
  const current = await json(await api(`/tasks/${activeTask.id}`));
  const raced = await Promise.all(['Concurrent acceptance A', 'Concurrent acceptance B'].map(description => api(`/tasks/${activeTask.id}`, 'PATCH', { description, expectedVersion: current.version })));
  assert.deepEqual(raced.map(response => response.status).sort(), [200, 409]);
  control = (await controls()).find(row => row.runId === lane.runId);
  for (let reconnect = 0; reconnect < 2; reconnect++) {
    const headers = new Headers(agentHeaders);
    if (reconnect) headers.set('last-event-id', `${control.id}:${control.revision}`);
    const stream = await fixture.app.request('/api/v1/daemons/events', { headers, signal: AbortSignal.timeout(3000) });
    assert.equal(stream.status, 200);
    const reader = stream.body!.getReader();
    let text = '';
    while (!text.includes(`id: ${control.id}:${control.revision}`)) {
      const next = await reader.read();
      assert.equal(next.done, false);
      text += new TextDecoder().decode(next.value);
    }
    await reader.cancel();
    assert.match(text, /event: requirement_execution_invalidated/);
  }
  assert.equal(control.deadline, deadline, 'coalescing edits must not reset the recovery budget');
  const ack = (phase: string) => api(`/daemons/${daemonA}/execution-controls/${control.id}/ack`, 'POST', { phase, revision: control.revision, workspace: { nodeId: 'node-a', state: 'dirty', summary: 'Preserved local edits' } }, agentHeaders);
  // A lost acknowledgement response can be retried, and delayed delivery cannot regress stop state.
  await json(await ack('received'));
  await json(await ack('received'));
  assert.equal((await api(`/daemons/${daemonA}/execution-controls/${control.id}/resume`, 'POST', {}, agentHeaders)).status, 400);
  await json(await ack('stopping'));
  await json(await ack('received'));
  assert.equal((await controls()).find(row => row.id === control.id).phase, 'stopping');
  await json(await ack('stopped'));
  await json(await ack('stopped'));
  await json(await ack('reconciling'));
  const resumed = await json(await api(`/daemons/${daemonA}/execution-controls/${control.id}/resume`, 'POST', {}, agentHeaders));
  assert.equal(resumed.requirement.id, requirement.id);
  assert.notEqual(resumed.runId, lane.runId);
  assert.equal(resumed.leaseGeneration, lane.leaseGeneration, 'lane ownership remains renewable across local assessment');
  assert.notEqual((await api(`/tasks/${activeTask.id}/status`, 'PATCH', { status: 'done', ...fence }, agentHeaders)).status, 200, 'old run cannot reuse retained lease generation');

  await task(requirement.id, 'Planning remains editable while an agent holds the lane');
  const predecessor = await create('Draft predecessor');
  await json(await api(`/requirements/${predecessor.id}`, 'PATCH', { status: 'draft' }));
  await task(predecessor.id, 'Immature predecessor');
  await json(await api(`/requirements/${requirement.id}/dependencies`, 'POST', { dependsOnRequirementId: predecessor.id, type: 'blocks' }), 201);
  control = (await controls()).find(row => row.runId === resumed.runId);
  const staleRevision = control.revision;
  await json(await api(`/tasks/${activeTask.id}`, 'PATCH', { description: 'Another edit while stop notifications are in flight' }));
  assert.equal((await api(`/daemons/${daemonA}/execution-controls/${control.id}/ack`, 'POST', { phase: 'received', revision: staleRevision }, agentHeaders)).status, 409);
  control = (await controls()).find(row => row.runId === resumed.runId);
  await json(await ack('received')); await json(await ack('stopping')); await json(await ack('stopped')); await json(await ack('reconciling'));
  const blocked = await json(await api(`/daemons/${daemonA}/execution-controls/${control.id}/resume`, 'POST', {}, agentHeaders));
  assert.equal(blocked.recovery, 'blocked');
  assert.equal(await db.query.requirementClaims.findFirst({ where: eq(requirementClaims.requirementId, requirement.id) }), undefined);
  const unrelated = await create('Unrelated eligible work'); await task(unrelated.id, 'Use free worker');
  assert.equal((await json(await acquire())).requirement.id, unrelated.id);

  // Bounded no-checkpoint restart is conservative and counts attempts transactionally.
  const recoverable = await create('Retry-safe failed node', { retrySafe: true, graceMs: 1000, maxAttempts: 1 });
  const recoverableTask = await task(recoverable.id, 'Reconstruct from durable inputs');
  const failedLane = await json(await acquire(daemonB));
  assert.equal(failedLane.requirement.id, recoverable.id);
  await json(await api(`/tasks/${recoverableTask.id}/claim`, 'POST', { durationMinutes: 30 }, agentHeaders), 201);
  const claim = (await db.query.requirementClaims.findFirst({ where: eq(requirementClaims.id, failedLane.runId) }))!;
  await db.update(daemons).set({ lastHeartbeatAt: new Date(Date.now() - 5000) }).where(eq(daemons.id, daemonB));
  await db.update(requirementClaims).set({ heartbeatAt: new Date(Date.now() - 5000), expiresAt: new Date(Date.now() - 1000) }).where(eq(requirementClaims.id, claim.id));
  await json(await api(`/requirements/${recoverable.id}/claim`));
  assert.equal(await db.query.taskClaims.findFirst({ where: eq(taskClaims.taskId, recoverableTask.id) }), undefined, 'old execution task claims must not block fenced takeover');
  // Free A's unrelated lane so its worker can demonstrate cross-node failover.
  await json(await api(`/requirements/${unrelated.id}/release`, 'POST', { daemonId: daemonA, leaseGeneration: (await db.query.requirementClaims.findFirst({ where: eq(requirementClaims.requirementId, unrelated.id) }))!.generation }, agentHeaders));
  const takeover = await json(await acquire());
  assert.equal(takeover.requirement.id, recoverable.id);
  assert.notEqual(takeover.runId, failedLane.runId);
  assert.ok(takeover.leaseGeneration > failedLane.leaseGeneration);
  assert.equal((await db.query.requirements.findFirst({ where: eq(requirements.id, recoverable.id) }))!.recoveryAttempts, 1);
  assert.equal((await db.query.executionControls.findFirst({ where: eq(executionControls.runId, failedLane.runId) }))!.reason, 'restart_with_possible_local_loss');
  assert.notEqual((await api(`/daemons/${daemonB}/execution-authority`, 'POST', { requirementId: recoverable.id, runId: failedLane.runId, leaseGeneration: failedLane.leaseGeneration }, agentHeaders)).status, 200);
  const expire = async (runId: string) => {
    const held = await db.query.requirementClaims.findFirst({ where: eq(requirementClaims.id, runId) });
    if (held?.daemonId) await db.update(daemons).set({ lastHeartbeatAt: new Date(Date.now() - 5000) }).where(eq(daemons.id, held.daemonId));
    await db.update(requirementClaims).set({ heartbeatAt: new Date(Date.now() - 5000), expiresAt: new Date(Date.now() - 1000) }).where(eq(requirementClaims.id, runId));
  };
  await expire(takeover.runId);
  assert.equal((await json(await acquire(daemonB))).requirement, null, 'exhausted budget must prevent another failover');
  assert.equal((await db.query.requirements.findFirst({ where: eq(requirements.id, recoverable.id) }))!.recoveryAttempts, 1);
  const exhausted = (await db.query.executionControls.findFirst({ where: eq(executionControls.runId, takeover.runId) }))!;
  assert.equal(exhausted.phase, 'manual');
  assert.match(exhausted.reason, /budget exhausted/);
  const unsafe = await create('Unknown external operation safety');
  const unsafeTask = await task(unsafe.id, 'Potential non-idempotent external action');
  const unsafeLane = await json(await acquire(daemonB));
  assert.equal(unsafeLane.requirement.id, unsafe.id);
  await expire(unsafeLane.runId);
  assert.equal((await json(await acquire())).requirement, null, 'unknown safety is not implicitly replay-safe');
  const unsafeControl = (await db.query.executionControls.findFirst({ where: eq(executionControls.runId, unsafeLane.runId) }))!;
  const inspected = await json(await api(`/requirements/${unsafe.id}`));
  assert.equal((await api(`/requirements/${unsafe.id}/execution-recovery`, 'POST', { controlId: unsafeControl.id, expectedPlanRevision: inspected.planRevision, reason: 'Verified external action did not occur; durable inputs remain available' }, agentHeaders)).status, 403);
  await json(await api(`/requirements/${unsafe.id}/execution-recovery`, 'POST', { controlId: unsafeControl.id, expectedPlanRevision: inspected.planRevision, reason: 'Verified external action did not occur; durable inputs remain available' }));
  const manualRestart = await json(await acquire());
  assert.equal(manualRestart.requirement.id, unsafe.id);
  const currentFence = { daemonId: daemonA, runId: manualRestart.runId, leaseGeneration: manualRestart.leaseGeneration };
  await json(await api(`/tasks/${unsafeTask.id}/status`, 'PATCH', { status: 'done', ...currentFence }, agentHeaders));
  await json(await api(`/tasks/${unsafeTask.id}`, 'PATCH', { description: 'New acceptance after completion' }));
  const changedEvidence = await json(await api(`/requirements/${unsafe.id}`));
  assert.equal(changedEvidence.evidenceNeedsReview, true);
  assert.equal((await api(`/requirements/${unsafe.id}/execution-revalidation`, 'POST', { expectedPlanRevision: changedEvidence.planRevision - 1, reason: 'Old inspection is stale' })).status, 409);
  await json(await api(`/requirements/${unsafe.id}/execution-revalidation`, 'POST', { expectedPlanRevision: changedEvidence.planRevision, reason: 'Inspected completed evidence against the new acceptance criteria' }));
  assert.equal((await json(await api(`/requirements/${unsafe.id}`))).evidenceNeedsReview, false);


  const gitRequirement = await json(await api(`/projects/${fixture.project.id}/requirements`, 'POST', { title: 'Git synchronization gate', status: 'approved', workflowPreset: 'git_branch' }), 201);
  const gitTask = await task(gitRequirement.id, 'Synchronize before completion');
  const repository = await json(await api('/repositories', 'POST', { host: 'github.com', namespace: 'fixture', name: 'sync', provider: 'github', visibility: 'private', ownerId: fixture.owner.context.actor.id, ownerType: 'human', defaultBranch: 'main' }), 201);
  await json(await api(`/requirements/${gitRequirement.id}/repositories`, 'POST', { repositoryId: repository.id, baseBranch: 'main', workingBranch: 'feature/sync' }), 201);
  const gitLane = await json(await acquire(daemonB));
  assert.equal(gitLane.requirement.id, gitRequirement.id);
  const gitCapability = await json(await api(`/daemons/${daemonB}/delegations`, 'POST', { requirementId: gitRequirement.id, taskId: gitTask.id, workerIndex: 0, runId: gitLane.runId, leaseGeneration: gitLane.leaseGeneration }, agentHeaders), 201);
  const gitChild = new Headers({ authorization: `Bearer ${gitCapability.token}`, 'content-type': 'application/json' });
  assert.equal((await api(`/tasks/${gitTask.id}/status`, 'PATCH', { status: 'done' }, gitChild)).status, 400, 'completion requires a recorded synchronization baseline');
  const syncInput = { requirementId: gitRequirement.id, runId: gitLane.runId, leaseGeneration: gitLane.leaseGeneration, repositoryId: repository.id, remoteTip: 'a'.repeat(40), localHead: 'b'.repeat(40), fetchedAt: new Date().toISOString() };
  assert.equal((await api(`/daemons/${daemonB}/git-synchronization`, 'POST', syncInput, gitChild)).status, 403);
  assert.equal((await api(`/daemons/${daemonB}/git-synchronization`, 'POST', { ...syncInput, fetchedAt: new Date(Date.now() - 600000).toISOString() }, agentHeaders)).status, 400);
  await json(await api(`/daemons/${daemonB}/git-synchronization`, 'POST', syncInput, agentHeaders));
  await json(await api(`/tasks/${gitTask.id}/status`, 'PATCH', { status: 'done' }, gitChild));
  await json(await api(`/requirements/${gitRequirement.id}`, 'PATCH', { description: 'Invalidate synchronization with a new execution input' }));
  assert.equal((await api(`/daemons/${daemonB}/git-synchronization`, 'POST', syncInput, agentHeaders)).status, 403);

  // A restarted supervisor on the same authenticated node can recover before cross-node grace.
  await json(await api(`/requirements/${gitRequirement.id}/release`, 'POST', { daemonId: daemonB, runId: gitLane.runId, leaseGeneration: gitLane.leaseGeneration }, agentHeaders));
  const localRecovery = await create('Original node returns before grace', { retrySafe: false, graceMs: 60000, maxAttempts: 1 });
  await task(localRecovery.id, 'Inspect retained local files');
  const originalLane = await json(await acquire(daemonB));
  assert.equal(originalLane.requirement.id, localRecovery.id);
  await db.update(requirementClaims).set({ expiresAt: new Date(Date.now() - 1) }).where(eq(requirementClaims.id, originalLane.runId));
  await json(await api(`/requirements/${localRecovery.id}/claim`));
  const returned = randomUUID();
  await json(await api('/daemons/register', 'POST', { id: returned, nodeId: 'node-b', name: 'Restarted supervisor', role: 'executor', capabilities: ['codex', 'executor:codex', 'live-plan-v1'] }, agentHeaders), 201);
  const localControls = (await json(await api(`/daemons/${returned}/execution-controls`, 'GET', undefined, agentHeaders))).items;
  const localControl = localControls.find((control: any) => control.runId === originalLane.runId);
  assert.ok(localControl);
  assert.ok(Date.parse(localControl.deadline) > Date.now());
  for (const phase of ['received', 'stopping', 'stopped', 'reconciling']) await json(await api(`/daemons/${returned}/execution-controls/${localControl.id}/ack`, 'POST', { phase, revision: localControl.revision, workspace: { nodeId: 'node-b', state: 'dirty', summary: 'Observed local termination and retained actual files' } }, agentHeaders));
  const returnedLane = await json(await api(`/daemons/${returned}/execution-controls/${localControl.id}/resume`, 'POST', { workerIndex: 0 }, agentHeaders));
  assert.equal(returnedLane.requirement.id, localRecovery.id);
  assert.notEqual(returnedLane.runId, originalLane.runId);
  assert.equal((await db.query.requirements.findFirst({ where: eq(requirements.id, localRecovery.id) }))!.recoveryAttempts, 0, 'same-node assessment does not consume a cross-node restart attempt');

});
